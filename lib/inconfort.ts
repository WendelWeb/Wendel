// L'INCONFORT EST LE CHEMIN — et la répétition est le travail.
//
// Deux choses qu'il a dites coup sur coup, et qui vont ensemble.
//
// La première corrige une erreur qui traverse toute l'app : jusqu'ici, tout
// traitait l'inconfort comme un péage — quelque chose à payer pour accéder à
// autre chose. Il dit l'inverse, et il a raison : la douleur qu'il sent EST le
// chemin, pas l'obstacle posé dessus. Ça change ce qu'il doit chercher. Un
// homme qui paie un péage cherche à en réduire le montant ; un homme qui
// marche cherche à avancer.
//
// La seconde est une instruction sur l'app elle-même : revenir, relire,
// répéter. C'est exact et c'est mécanique — le circuit qu'il veut épaissir ne
// s'épaissit que par la répétition. Rien de moral là-dedans.
//

// LA LOI — ce qui décide vraiment, et qui n'a rien de religieux.
//
// C'est le rappel qu'il a demandé, et c'est le plus dur de tous parce qu'il
// lui retire son dernier abri : tant que la promesse reçue sur la montagne
// reste au centre, il peut attendre. Une promesse, ça s'attend. Une loi
// physique, non — elle s'applique, ou elle ne s'applique pas, selon ce qu'on
// fait de son corps.
//
// Il l'a formulé lui-même : ce n'est pas ce que Dieu a dit ni ce qu'Il a
// promis, c'est à quel point il se maîtrise. Et il l'a prouvé par l'exemple
// inverse — des hommes qui ne Le connaissent pas, qui n'ont aucune crainte de
// Lui, bâtissent des empires ; des hommes qui prient chaque jour échouent
// chaque jour.
//
// La conclusion n'est pas que Dieu ne compte pas. C'est que Sa propre
// instruction, à lui, portait sur l'énergie — pas sur la piété.
//
// Client-safe.


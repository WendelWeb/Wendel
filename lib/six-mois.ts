// SIX MOIS — le calcul qu'il n'avait jamais posé.
//
// Tout le reste de l'app lui dit ce qu'il perd. Ce module-ci lui dit ce qu'il
// ACHÈTE avec ce qu'il perd — et le prix est ridicule. C'est un angle que rien
// d'autre ne couvrait.
//
// Une correction est intégrée, et elle est délibérée. Il l'a formulé ainsi :
// « dans six mois je pourrai baiser toutes les femmes que je veux ». Écrit tel
// quel, c'est une promesse que la réalité ne signera pas — six mois ne font ni
// les 90 kg, ni l'argent, ni les voitures, et la rétention seule ne produit
// aucune attirance. Le danger est mécanique : un argument qui sur-promet lui
// fournit son excuse au mois six, le jour où le compte ne tombe pas juste.
//
// La version écrite ici porte donc sur ce qu'il DEVIENT, pas sur ce que
// d'autres décideront — puisque ça, il ne le contrôle pas. Six mois ne lui
// donnent pas les femmes : ils lui donnent l'homme pour qui ce n'est plus un
// problème. C'est plus vrai, et c'est plus dur à contourner.
//
// Sa ligne du un pour cent est gardée telle quelle. Elle n'a besoin d'aucune
// aide : elle compare deux choses qu'il contrôle entièrement, et le rapport
// est absurde dans un seul sens.
//
// Client-safe.


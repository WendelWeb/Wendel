// LE ROI — ce qui a été dit sur lui, et ce que ça rend impossible.
//
// Ses mots : Dieu a réellement parlé à l'un de Ses serviteurs et a appelé
// Wendel « roi ». Un autre jour, Il l'a appelé « Son fils ». Et sa question :
// si je suis fils de Dieu, je suis de Sa nature — pas pour m'en orgueillir,
// mais parce que c'est la loi de la nature, les lions n'accouchent pas de
// chiens. Alors : est-ce que c'est ça qu'un dieu fait ? Est-ce qu'un dieu a
// besoin de dopamine TikTok ? Est-ce qu'un dieu se masturbe ? Est-ce qu'un roi
// quémande ?
//
// La forme de l'argument est ce qui le rend fort, et il faut la préserver
// exactement. Un orgueil dirait : je suis roi, donc je mérite. Lui dit : je
// suis roi, donc cette conduite est IMPOSSIBLE. Ce n'est pas une revendication
// de droits, c'est une erreur de catégorie qu'on lui met sous les yeux. Le
// reste de l'app lui dit ce qu'il perd ou ce qu'il achète ; ce module-ci lui
// dit qu'il se trompe d'espèce.
//
// Il a lui-même posé le garde-fou — « pas du tout pour m'en orgueillir » — et
// le module le tient : un titre ne confère pas, il oblige. Un fils qui vit
// ainsi ne réfute pas la filiation, il la déshonore. C'est plus dur que la
// version orgueilleuse, et c'est la seule qui travaille.
//
// Les ancrages scripturaires sont donnés avec leurs références parce qu'ils
// existent réellement et qu'ils sont vérifiables : sans elles, ce module ne
// serait qu'une exaltation de plus, et il en a déjà trop lu.
//
// Client-safe.


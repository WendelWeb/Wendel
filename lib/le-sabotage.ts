// LE SABOTAGE — ce qui arriverait si tout lui était donné aujourd'hui.
//
// Ses mots : « tant que tu ne maîtrises pas ta chair, tes pulsions, ta
// discipline — même si Dieu se présentait devant toi et te donnait tout ce que
// tu as écrit, tu le saboterais. Tant que tu ne contrôles pas tes pulsions,
// rien ne te sera possible. D'ailleurs Dieu te les a déjà donnés. »
//
// C'est l'argument le plus dur de toute l'app, et il ne double rien.
//
// lib/instrument.ts dit : Dieu pourrait t'employer, mais Il ne trouve pas ta
// main libre. C'est une question d'utilité — il n'est pas disponible.
// Ce module dit autre chose, et de pire : même en le lui donnant, ça ne
// tiendrait pas. Ce n'est plus une question de disponibilité mais de capacité
// de garde. Un vaisseau percé ne se remplit pas, quelle que soit la source.
//
// Et la dernière clause est la charnière de tout : « Il te les a déjà donnés ».
// Elle déplace l'attente. Il ne manque pas la provision — il manque la garde.
// Ce n'est donc pas Dieu qu'il attend : c'est lui-même. Tant que ce n'est pas
// écrit, l'homme peut prier en attendant ; une fois écrit, il n'a plus qu'à
// tenir.
//
// Client-safe.


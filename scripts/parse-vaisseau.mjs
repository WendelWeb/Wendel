// Parses content/vaisseau.txt (extracted from le-vaisseau.docx) into a
// structured chapters JSON the app can read. Splits the body using the exact
// chapter titles from the table of contents, matched in order.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const raw = readFileSync("content/vaisseau.txt", "utf8");
const lines = raw.split("\n").map((l) => l.trim());

const norm = (s) =>
  s
    .replace(/[–—]/g, "-")
    .replace(/[’‘]/g, "'")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();

// --- 1. The body begins at the first ALL-CAPS "LIVRE" heading. ---
const bodyStart = lines.findIndex((l) => /^LIVRE\b/.test(l));

// --- 2. TOC = numbered entries before the body (they live in the Sommaire). ---
const toc = [];
for (let i = 0; i < bodyStart; i++) {
  const m = lines[i].match(/^(\d+)\.\s+(.+)$/);
  if (m) toc.push({ n: Number(m[1]), title: m[2].trim() });
}
const chapters = [];
let cur = null;
let p = 0;
let currentBook = "";
let expectBookTitle = false;

const pushCur = () => {
  if (cur) {
    cur.paragraphs = cur.paragraphs.filter((x) => x.length > 0);
    chapters.push(cur);
  }
};

for (let i = bodyStart; i < lines.length; i++) {
  const L = lines[i];
  if (!L) continue;

  const livre = L.match(/^LIVRE\s+([IVX]+)\b/);
  if (livre) {
    expectBookTitle = true;
    currentBook = `Livre ${livre[1]}`;
    continue;
  }
  if (expectBookTitle) {
    currentBook = `${currentBook} · ${L}`;
    expectBookTitle = false;
    continue;
  }
  if (/^ÉPILOGUE/i.test(L)) {
    pushCur();
    cur = { n: 130, book: "Épilogue", title: "Tu y es", paragraphs: [] };
    p = toc.length; // stop matching chapter titles
    continue;
  }
  if (p < toc.length && norm(L) === norm(toc[p].title)) {
    pushCur();
    cur = {
      n: toc[p].n,
      book: currentBook,
      title: toc[p].title,
      paragraphs: [],
    };
    p++;
    continue;
  }
  if (/^Chapitre\s+\d+$/i.test(L)) continue; // label line before a title
  if (cur) cur.paragraphs.push(L);
}
pushCur();

mkdirSync("content", { recursive: true });
writeFileSync(
  "content/vaisseau-chapters.json",
  JSON.stringify(chapters, null, 0),
  "utf8",
);

// Lightweight metadata (no body) for TOC + verdict engine.
const meta = chapters.map((c) => ({ n: c.n, book: c.book, title: c.title }));
writeFileSync(
  "lib/vaisseau-meta.ts",
  `// AUTO-GENERATED by scripts/parse-vaisseau.mjs — do not edit by hand.\n` +
    `export interface ChapterMeta { n: number; book: string; title: string; }\n` +
    `export const CHAPTER_META: ChapterMeta[] = ${JSON.stringify(meta, null, 2)};\n` +
    `export const CHAPTER_TITLES: Record<number, string> = Object.fromEntries(\n` +
    `  CHAPTER_META.map((c) => [c.n, c.title]),\n);\n`,
  "utf8",
);

// --- 3. Report / validate ---
console.log("TOC entries:", toc.length);
console.log("Chapters parsed:", chapters.length);
const found = new Set(chapters.map((c) => c.n));
const missing = toc.filter((t) => !found.has(t.n)).map((t) => t.n);
console.log("Missing chapter numbers:", missing.length ? missing.join(",") : "none");
for (const n of [1, 32, 77, 117, 120, 129]) {
  const c = chapters.find((x) => x.n === n);
  console.log(
    `ch${n}:`,
    c ? `"${c.title}" (${c.paragraphs.length} paras, book="${c.book}")` : "NOT FOUND",
  );
}
